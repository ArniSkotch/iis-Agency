SYSTEM_PROMPTS: dict[str, str] = {
    "analyst": ANALYST_PROMPT,
    "verifier": VERIFIER_PROMPT,
    "clarifier": CLARIFIER_PROMPT,
    "consultant": CONSULTANT_PROMPT,
    "comparer": COMPARER_PROMPT,
}


def format_chunks(chunks: list[Chunk]) -> str:
    """Развернуть найденные фрагменты в текстовый блок. Готово, менять не нужно."""
    if not chunks:
        return "(база знаний ничего не вернула)"
    # Страница печатается, только когда она есть: у markdown и текстовых файлов
    # page = 0, и «стр. 0» в каждом фрагменте учит модель дописывать в ссылку
    # номер, которого в контексте нет.
    return "\n\n".join(
        f"[{c.source}, стр. {c.page}] (близость {c.score})\n{c.text}" if c.page
        else f"[{c.source}] (близость {c.score})\n{c.text}"
        for c in chunks
    )


def build_messages(
    role: str,
    question: str,
    chunks: list[Chunk],
    history: list[Message],
) -> list[dict]:
    """Собрать список сообщений для LLM в строгом порядке: system -> history -> user."""
    system_prompt = SYSTEM_PROMPTS.get(role) or SYSTEM_PROMPTS["analyst"]

    messages: list[dict] = [
        {"role": "system", "content": system_prompt},
    ]

    for item in history:
        messages.append({
            "role": item.role,
            "content": item.content,
        })

    formatted_chunks = format_chunks(chunks)
    user_content = (
        f"Найденные фрагменты:\n{formatted_chunks}\n\n"
        f"Вопрос пользователя:\n{question}"
    )
    messages.append({
        "role": "user",
        "content": user_content,
    })

    return messages
